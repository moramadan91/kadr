// Builds the bundled Google Fonts set and the full catalog. Run: node scripts/fonts.mjs
// Bundled: every family with Arabic + the most popular Latin families (open-source licences only: OFL / Apache / UFL).
// Every other Google family is listed in src/fontcat.js and downloads inside the app on first use.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'src/fonts/gf'), LATIN = 150, SKIP = new Set(['Cairo']); // Cairo ships separately (UI font)

const get = async (u, kind = 'json') => {
  for (let i = 0; ; i++) {
    try {
      const r = await fetch(u);
      if (!r.ok) throw new Error(r.status + ' ' + u);
      return kind === 'json' ? JSON.parse((await r.text()).replace(/^\)\]\}'\s*/, '')) : Buffer.from(await r.arrayBuffer());
    } catch (e) { if (i >= 4) throw e; await new Promise(r => setTimeout(r, 1500 * (i + 1))); }
  }
};
export const WEIGHTS = { Thin: 100, ExtraLight: 200, Light: 300, Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800, Black: 900 };
// Files worth keeping from a family's download manifest: the upright variable font, else upright statics.
export function pickFiles(refs) {
  const tt = refs.filter(f => /\.ttf$/i.test(f.filename) && !/italic/i.test(f.filename));
  const vf = tt.filter(f => !f.filename.startsWith('static/') && /\[.*\]|VariableFont/.test(f.filename));
  if (vf.length) return vf.slice(0, 1);
  // statics: base optical size only (skip Family_24pt-…), regular / bold / black
  return tt.filter(f => { const n = path.basename(f.filename), w = (n.match(/-([A-Za-z]+)\.ttf$/) || [])[1]; return !/_\d+pt/.test(n) && (!w || [400, 700, 900].includes(WEIGHTS[w])); });
}
export function faceOf(family, file, wrange) {
  if (/\[.*\]|VariableFont/.test(file)) return { weight: wrange || '100 900' };
  const w = (file.match(/-([A-Za-z]+)\.ttf$/) || [])[1];
  return { weight: String(WEIGHTS[w] || 400) };
}
const slug = f => f.replace(/[^A-Za-z0-9]+/g, '');

const meta = await get('https://fonts.google.com/metadata/fonts');
const ok = f => f.isOpenSource && !f.isBrandFont && !/^(Material|Noto Color|Noto Emoji)/.test(f.family);
const all = meta.familyMetadataList.filter(ok);
const isAr = f => (f.subsets || []).includes('arabic');
const latin = all.filter(f => !isAr(f) && !f.isNoto && (f.subsets || []).includes('latin')).sort((a, b) => a.popularity - b.popularity).slice(0, LATIN);
const bundle = [...all.filter(isAr), ...latin].filter(f => !SKIP.has(f.family));
const wr = f => { const a = (f.axes || []).find(x => x.tag === 'wght'); return a ? `${a.min} ${a.max}` : null; };

fs.mkdirSync(OUT, { recursive: true });
const css = [], done = new Set();
let n = 0;
for (const f of bundle) {
  const dir = path.join(OUT, slug(f.family));
  const list = await get('https://fonts.google.com/download/list?family=' + encodeURIComponent(f.family));
  const files = pickFiles(list.manifest.fileRefs || []);
  if (!files.length) { console.warn('no files', f.family); continue; }
  fs.mkdirSync(dir, { recursive: true });
  for (const lic of list.manifest.files || []) if (/LICENSE|OFL/i.test(lic.filename)) fs.writeFileSync(path.join(dir, path.basename(lic.filename)), lic.contents);
  for (const r of files) {
    const name = path.basename(r.filename), dest = path.join(dir, name);
    if (!fs.existsSync(dest)) fs.writeFileSync(dest, await get(r.url, 'bin'));
    css.push(`@font-face { font-family: '${f.family}'; src: url('${slug(f.family)}/${encodeURIComponent(name)}'); font-weight: ${faceOf(f.family, name, wr(f)).weight}; font-display: block; }`);
  }
  done.add(f.family);
  if (++n % 20 === 0) console.log(n, '/', bundle.length);
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), css.join('\n') + '\n');
// Catalog: [family, category letter, flags] — a = Arabic, b = bundled (c = Cairo, bundled separately)
const cat = all.map(f => [f.family, (f.category || 'S')[0], (isAr(f) ? 'a' : '') + (done.has(f.family) || SKIP.has(f.family) ? 'b' : '')]);
fs.writeFileSync(path.join(ROOT, 'src/fontcat.js'), '// Generated by scripts/fonts.mjs — Google Fonts catalog.\nwindow.FONT_CAT = ' + JSON.stringify(cat) + ';\n');
console.log('bundled', done.size, 'catalog', cat.length);
